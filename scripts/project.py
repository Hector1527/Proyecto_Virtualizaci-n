#!/usr/bin/env python3
"""Render team templates and synchronize ConfigMaps from canonical sources."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKEN = '__ID_EQUIPO__'
SECRET_KEYS = (
    'POSTGRES_ADMIN_USER', 'POSTGRES_ADMIN_PASSWORD',
    'INVENTARIO_DB_USER', 'INVENTARIO_DB_PASSWORD',
    'CLIENTES_DB_USER', 'CLIENTES_DB_PASSWORD',
    'PEDIDOS_DB_USER', 'PEDIDOS_DB_PASSWORD',
)


def validate_id(team):
    if len(team) > 40 or not re.fullmatch(r'[a-z0-9](?:[a-z0-9-]*[a-z0-9])?', team):
        raise ValueError('ID: 1-40 caracteres, minúsculas, números o guiones; extremos alfanuméricos.')
    return team


def configmap(name, entries):
    lines = ['# Generated by scripts/project.py; edit the source files and regenerate.',
             'apiVersion: v1', 'kind: ConfigMap', 'metadata:',
             f'  name: {name}-{TOKEN}', f'  namespace: proyecto-2-{TOKEN}',
             '  labels:', '    project: el-quetzal', f'    team: {TOKEN}', 'data:']
    for key, value in entries.items():
        lines.append(f'  {key}: |')
        lines.extend('    ' + line if line else '' for line in value.splitlines())
    return '\n'.join(lines) + '\n'


def postgres_entries():
    entries = {'init-databases.sh': (ROOT / 'postgres-init/init-databases.sh').read_text(encoding='utf-8')}
    for folder in ('schema', 'seeds'):
        for source in sorted((ROOT / 'postgres-init' / folder).glob('*.sql')):
            entries[f'{folder}-{source.name}'] = source.read_text(encoding='utf-8')
    return entries


def generated_maps():
    return {
        Path('config/postgres-init-configmap.yaml'): configmap('postgres-init', postgres_entries()),
        Path('gateway/gateway-configmap.yaml'): configmap('gateway-config', {
            'nginx.conf': (ROOT / 'gateway/nginx.conf').read_text(encoding='utf-8'),
        }),
    }


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8', newline='\n')


def configure(team):
    validate_id(team)
    destination = ROOT / '.generated' / team
    sources = {p.relative_to(ROOT / 'k8s'): p.read_text(encoding='utf-8')
               for p in (ROOT / 'k8s').rglob('*.yaml')}
    sources.update(generated_maps())
    for path, content in sources.items():
        write(destination / 'k8s' / path, content.replace(TOKEN, team))
    write(destination / 'gateway/nginx.conf',
          (ROOT / 'gateway/nginx.conf').read_text(encoding='utf-8').replace(TOKEN, team))
    print(f'Configuración generada: .generated/{team}/k8s (plantillas conservadas).')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['configure', 'sync-configmaps'])
    parser.add_argument('team', nargs='?')
    args = parser.parse_args()
    if args.action == 'configure':
        if not args.team:
            parser.error('Falta el ID del equipo.')
        configure(args.team)
    else:
        for path, content in generated_maps().items():
            write(ROOT / 'k8s' / path, content)
        print('ConfigMaps sincronizados con gateway/ y postgres-init/.')


if __name__ == '__main__':
    try:
        main()
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc
